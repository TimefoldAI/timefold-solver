package ai.timefold.solver.core.impl.heuristic.selector;

import java.util.Spliterator;
import java.util.Spliterators;

import ai.timefold.solver.core.impl.heuristic.selector.common.decorator.SelectionProbabilityWeightFactory;

public interface IterableSelector<Solution_, T> extends Selector<Solution_>, Iterable<T> {

    /**
     * The approximate number of distinct selections: elements or moves distinct by their defining parameters,
     * not by the solutions they lead to; a move and its mirror (such as swap (A, B) and (B, A)) may count once or twice.
     * A random JIT {@link Selector} with {@link #isNeverEnding()} true should return a size
     * as if it would be able to return each distinct element only once,
     * because the size can be used in {@link SelectionProbabilityWeightFactory}.
     * An upper bound gives the best bail-out behavior of filtering selectors, which multiply the size.
     * <p>
     * The size is never negative. When the count does not fit in a long, it is {@link Long#MAX_VALUE},
     * meaning "at least this many"; callers therefore combine sizes with saturating arithmetic
     * and never treat a size as exact.
     * An {@link UnsupportedOperationException} signals an unknown size.
     * <p>
     * This may be called on every step, for example to compute a bail-out.
     * It need not be cheap, but a slow implementation slows the solver down.
     *
     * @return the approximate number of elements generated by this {@link Selector}, always {@code >= 0}
     */
    long getSize();

    @Override
    default Spliterator<T> spliterator() {
        return Spliterators.spliterator(iterator(), getSize(), Spliterator.ORDERED);
    }
}
